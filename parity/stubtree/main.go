// Command stubtree runs the unmodified Python test suite against the Go binary (plan 3.7, step 1).
//
//	go run ./parity/stubtree -repo . -binary /abs/harness -manifest parity/manifest/wal.json [-keep] [-- unittest args]
//
// It copies the repo into a temp tree and replaces each ported script named by the manifest with an exec
// stub. Run as a script, the stub records the call in $PARITY_COUNTER and execs Go with the canonical
// grammar. Imported as a module (a library importer such as rescue importing wal), it loads the original
// file and installs it in sys.modules, so importers see the Python implementation unchanged. After the
// suite, every manifest entry with min_calls must have reached Go that often, so a pass that never touched
// Go cannot count as parity.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Manifest lists one switch group's ported entry points.
type Manifest struct {
	Group   string  `json:"group"`
	Host    string  `json:"host"`
	Entries []Entry `json:"entries"`
}

// Entry maps a Python script to the Go subcommand that replaces it.
type Entry struct {
	Script   string   `json:"script"`    // repo-relative, e.g. harness/hooks/wal_note.py
	Sub      []string `json:"sub"`       // Go subcommand prefix, e.g. ["wal-note"]
	MinCalls int      `json:"min_calls"` // the suite must exec this stub at least this often
}

const stubTemplate = `# parity stub generated by parity/stubtree; the original is %[1]s
import os, sys
if __name__ == "__main__":
    counter = os.environ.get("PARITY_COUNTER")
    if counter:
        with open(counter, "a", encoding="utf-8") as handle:
            handle.write(%[2]q + "\n")
    here = os.path.abspath(__file__)
    os.execv(%[3]q, [%[3]q, "--host", %[4]q, "--config-dir", os.path.dirname(here), "--entry", "py:" + here, %[5]s *sys.argv[1:]])
else:
    import importlib.util
    _spec = importlib.util.spec_from_file_location(__name__, os.path.join(os.path.dirname(os.path.abspath(__file__)), %[1]q))
    _module = importlib.util.module_from_spec(_spec)
    sys.modules[__name__] = _module
    _spec.loader.exec_module(_module)
`

func main() {
	repo := flag.String("repo", ".", "repository root")
	binary := flag.String("binary", "", "absolute path of the Go harness binary")
	manifestPath := flag.String("manifest", "", "parity manifest JSON")
	keep := flag.Bool("keep", false, "keep the temp tree")
	flag.Parse()
	code, err := run(*repo, *binary, *manifestPath, *keep, flag.Args(), os.Stdout, os.Stderr)
	if err != nil {
		fmt.Fprintln(os.Stderr, "stubtree:", err)
		os.Exit(2)
	}
	os.Exit(code)
}

func run(repo, binary, manifestPath string, keep bool, unittestArgs []string, stdout, stderr io.Writer) (int, error) {
	if !filepath.IsAbs(binary) {
		return 2, fmt.Errorf("-binary must be absolute")
	}
	raw, err := os.ReadFile(manifestPath)
	if err != nil {
		return 2, err
	}
	var m Manifest
	if err := json.Unmarshal(raw, &m); err != nil || m.Group == "" || m.Host == "" || len(m.Entries) == 0 {
		return 2, fmt.Errorf("invalid manifest %s", manifestPath)
	}
	tree, err := os.MkdirTemp("", "parity-"+m.Group+"-")
	if err != nil {
		return 2, err
	}
	if !keep {
		defer os.RemoveAll(tree)
	} else {
		fmt.Fprintln(stderr, "stubtree: tree kept at", tree)
	}
	if err := copyTree(repo, tree); err != nil {
		return 2, err
	}
	for _, e := range m.Entries {
		if err := stub(tree, binary, m.Host, e); err != nil {
			return 2, err
		}
	}
	counter := filepath.Join(tree, ".parity-counter")
	args := append([]string{"-m", "unittest"}, unittestArgs...)
	if len(unittestArgs) == 0 {
		args = append(args, "discover", "-s", "tests")
	}
	cmd := exec.Command("python3", args...)
	cmd.Dir = tree
	cmd.Stdout, cmd.Stderr = stdout, stderr
	cmd.Env = append(os.Environ(), "PARITY_COUNTER="+counter, "PYTHONDONTWRITEBYTECODE=1")
	runErr := cmd.Run()
	code := 0
	if runErr != nil {
		code = 1
		if ee, ok := runErr.(*exec.ExitError); ok {
			code = ee.ExitCode()
		} else {
			return 2, runErr
		}
	}
	calls := map[string]int{}
	if f, err := os.Open(counter); err == nil {
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			calls[sc.Text()]++
		}
		f.Close()
	}
	for _, e := range m.Entries {
		fmt.Fprintf(stderr, "stubtree: %s reached Go %d time(s)\n", e.Script, calls[e.Script])
		if calls[e.Script] < e.MinCalls {
			fmt.Fprintf(stderr, "stubtree: FAIL %s reached Go %d < min_calls %d; a Python pass is not Go parity\n", e.Script, calls[e.Script], e.MinCalls)
			if code == 0 {
				code = 3
			}
		}
	}
	return code, nil
}

func stub(tree, binary, host string, e Entry) error {
	if filepath.IsAbs(e.Script) || strings.Contains(e.Script, "..") || !strings.HasSuffix(e.Script, ".py") {
		return fmt.Errorf("bad script %q", e.Script)
	}
	path := filepath.Join(tree, filepath.FromSlash(e.Script))
	original := "_parity_original_" + filepath.Base(path)
	if err := os.Rename(path, filepath.Join(filepath.Dir(path), original)); err != nil {
		return err
	}
	var sub strings.Builder
	for _, s := range e.Sub {
		fmt.Fprintf(&sub, "%q, ", s)
	}
	body := fmt.Sprintf(stubTemplate, original, e.Script, binary, host, sub.String())
	return os.WriteFile(path, []byte(body), 0o755)
}

// copyTree copies regular files and directories, skipping .git and caches; symlinks are recreated as-is.
func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		if d.IsDir() && (d.Name() == ".git" || d.Name() == "__pycache__" || d.Name() == "node_modules") && rel != "." {
			return filepath.SkipDir
		}
		target := filepath.Join(dst, rel)
		info, err := d.Info()
		if err != nil {
			return err
		}
		switch {
		case d.IsDir():
			return os.MkdirAll(target, 0o755)
		case info.Mode()&fs.ModeSymlink != 0:
			link, err := os.Readlink(p)
			if err != nil {
				return err
			}
			return os.Symlink(link, target)
		case info.Mode().IsRegular():
			in, err := os.Open(p)
			if err != nil {
				return err
			}
			defer in.Close()
			out, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, info.Mode().Perm())
			if err != nil {
				return err
			}
			if _, err := io.Copy(out, in); err != nil {
				out.Close()
				return err
			}
			return out.Close()
		}
		return nil
	})
}
